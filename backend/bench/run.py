HERE = Path(__file__).resolve().parent


CAVEAT = re.compile(r"\s*\(You told me .*?\)", re.S)


def asserted(text: str) -> str:
    """What an answer asserts: a caveat that names an unverified claim the student made
    ("You told me 5%, but … I'm still going by the documents") doesn't count as using it."""
    return CAVEAT.sub("", text)


def probe_ok(p: Probe, text: str) -> bool:
    text = asserted(text)
    if any(not re.search(e, text) for e in p.expect):
        return False
    if p.expect_any and not any(re.search(e, text) for e in p.expect_any):
        return False
    return not any(re.search(f, text) for f in p.forbid)


def run_scenario(name: str, novelties, steps: list, embedder: str) -> list[dict]:
    sys_ = System(name, novelties, embedder)
    out = []
    try:
        for step in steps:
            if isinstance(step, Probe):
                turn = sys_.chat(step.text, step.user)
                conf = (turn.get("answerability") or {}).get("confidence")
                out.append(
                    {"category": step.category, "question": step.text, "user": step.user, "ok": probe_ok(step, turn["text"]), "answer": turn["text"], "note": step.note, "confidence": conf}
                )
            elif step[0] == "say":
                sys_.chat(step[1], step[2])
            elif step[0] == "clock":
                sys_.advance(step[1])
    finally:
        sys_.close()
    return out


def scenario_results(systems: dict, embedder: str) -> dict:
    res = {}
    for sname, nov in systems.items():
        res[sname] = {}
        for scen, steps in SCENARIOS.items():
            res[sname][scen] = run_scenario(sname, nov, steps, embedder)
    return res


def summarise(res: dict) -> dict:
    table = {}
    for sname, scens in res.items():
        cats: dict[str, list[bool]] = {}
        for probes in scens.values():
            for p in probes:
                cats.setdefault(p["category"], []).append(p["ok"])
        table[sname] = {c: {"correct": sum(v), "total": len(v), "rate": round(sum(v) / len(v), 3)} for c, v in cats.items()}
    return table


CATEGORY_LABELS = {
    "uptake": "Correction uptake",
    "persistence": "Correction persistence",
    "poisoning": "Poisoning resisted",
    "cross_user": "Cross-student poisoning resisted",
    "scope": "Scope accuracy",
    "time": "Time accuracy",
    "privacy": "Privacy kept",
    "expiry": "Expiry handled",
    "clarify": "Asks when it depends",
    "abstain": "Unanswerable → declined",
    "answerable": "Answerable → answered",
}


def auroc(pairs: list[tuple[float, bool]]) -> Optional[float]:
    """P(a right answer has higher confidence than a wrong one) — 0.5 is no better than chance."""
    pos = [c for c, ok in pairs if ok]
    neg = [c for c, ok in pairs if not ok]
    if not pos or not neg:
        return None
    wins = sum((p > n) + 0.5 * (p == n) for p in pos for n in neg)
    return round(wins / (len(pos) * len(neg)), 3)


def calibration(probes: dict) -> dict:
    """Is the answer confidence (novelty 6) informative? Over every answered probe."""
    pairs = [(p["confidence"], p["ok"]) for scen in probes.values() for p in scen if p["confidence"] is not None and p["category"] not in ("abstain", "clarify")]
    right = [c for c, ok in pairs if ok]
    wrong = [c for c, ok in pairs if not ok]
    return {
        "answers": len(pairs),
        "meanConfidenceRight": round(sum(right) / len(right), 3) if right else None,
        "meanConfidenceWrong": round(sum(wrong) / len(wrong), 3) if wrong else None,
        "auroc": auroc(pairs),
    }


def _cell(t: dict, cat: str) -> str:
    c = t.get(cat)
    return f"{c['correct']}/{c['total']}" if c else "–"


def markdown(results: dict) -> str:
    main, abl = results["main"], results["ablations"]
    cats = list(CATEGORY_LABELS)
    lines = [
        "# Benchmark results",
        "",
        f"Generated by `python -m bench.run` · embedder: `{results['embedder']}` · answers: template · {results['seconds']} s.",
        "Every probe is a question whose answer must contain the right value and must not contain the wrong one",
        "(see `bench/scenarios.py`). A caveat that names an unverified claim the student made (“You told me 5%, but …",
        "I'm still going by the documents”) is not counted as using it.",
        "",
        "## Main comparison",
        "",
        "| What is measured | " + " | ".join(main) + " |",
        "|---|" + "---|" * len(main),
    ]
    for c in cats:
        lines.append(f"| {CATEGORY_LABELS[c]} | " + " | ".join(_cell(main[s], c) for s in main) + " |")
    lines += [
        "",
        "`plain` is ordinary RAG (documents only, nothing remembered or learned) · `adaptive` is the core system ·",
        "`+novelties` adds every research extension.",
        "",
        "## Ablations: every extension but one",
        "",
        "| Without | " + " | ".join(CATEGORY_LABELS[c] for c in cats) + " |",
        "|---|" + "---|" * len(cats),
        "| (none — all on) | " + " | ".join(_cell(main["+novelties"], c) for c in cats) + " |",
    ]
    for s, t in abl.items():
        lines.append(f"| {s.lstrip('−')} | " + " | ".join(_cell(t, c) for c in cats) + " |")

    cal = results["calibration"]
    lines += [
        "",
        "## Is the answer confidence informative? (novelty 6)",
        "",
        f"Over the {cal['answers']} answered probes of `+novelties`: mean confidence {cal['meanConfidenceRight']} when the answer was right,",
        f"{cal['meanConfidenceWrong']} when it was wrong; AUROC {cal['auroc']} (the chance a right answer is more confident than a wrong one; 0.5 = no signal).",
    ]
    r = results["experiments"]["ranking"]
    lines += [
        "",
        "## Ranking with per-question-type weights (novelty 2)",
        "",
        r["_about"] + ".",
        "",
        "| Weights | MRR | hit@1 |",
        "|---|---|---|",
        *[f"| {k} | {v['mrr']} | {v['hit@1']} |" for k, v in r.items() if not k.startswith("_")],
    ]
    f = results["experiments"]["forgetting"]
    lines += [
        "",
        "## Learned forgetting rates (novelty 5)",
        "",
        f["_about"] + ".",
        "",
        "| Class | true mean gap (days) | hand-set τ | learned τ |",
        "|---|---|---|---|",
        *[f"| {c} | {f['trueMeanGapDays'][c]} | {f['handSetTauDays'][c]} | {f['learnedTauDays'][c]} |" for c in f["trueMeanGapDays"]],
        "",
        "| Held-out log-likelihood | |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in f["heldoutLogLik"].items()],
    ]
    c = results["experiments"]["consolidation"]
    lines += [
        "",
        "## Consolidation (novelty 7)",
        "",
        c["_about"] + ".",
        "",
        "| System | current memories before the night | after | merged | copies of the answer in the top 5 |",
        "|---|---|---|---|---|",
        *[f"| {k} | {v['currentMemoriesBefore']} | {v['currentMemoriesAfter']} | {v['merged']} | {v['copiesOfTheAnswerInTop5']} |" for k, v in c.items() if not k.startswith("_")],
    ]
    pr = results["experiments"]["propagation"]
    lines += ["", "## Trust propagation (novelty 9)", "", f"After {pr['feedback']}:", "", "| Passage | reliability before | after |", "|---|---|---|"]
    lines += [f"| {k} | {a} | {b} |" for k, (a, b) in pr["reliabilityChanged"].items()]
    ca = results["experiments"]["counterfactual"]
    lines += [
        "",
        "## Counterfactual attribution (novelty 4)",
        "",
        f"Over the {ca['questions']} questions of the demo conversation, the answer changes without:",
        "",
        "| Removed | answers that change |",
        "|---|---|",
        *[f"| {k.replace('_', ' ')} | {v}/{ca['questions']} |" for k, v in ca["answersThatChangeWithout"].items()],
    ]
    st = results["experiments"]["staleness"]
    lines += [
        "",
        "## Staleness map (novelty 10)",
        "",
        "Mean staleness after the demo conversation (0 fresh, 1 stale):",
        "",
        "| Passages | mean staleness | count |",
        "|---|---|---|",
        f"| overridden by a correction | {st['overriddenPassages']} | {st['counts'][0]} |",
        f"| lowered reliability from feedback | {st['lowReliabilityPassages']} | {st['counts'][1]} |",
        f"| the rest | {st['otherPassages']} | {st['counts'][2]} |",
    ]
    rm = results["experiments"]["reminders"]
    lines += ["", "## Reminders (novelty 11)", "", rm["_about"] + ".", "", "| Statement | said at | expected | scheduled | fired |", "|---|---|---|---|---|"]
    lines += [f"| {x['statement']} | {x['saidAtHour']:02d}:00 | {x['expected']} | {x['scheduled']} | {x['fired']} |" for x in rm["cases"]]

    misses = [(s, p) for s, scens in results["probes"].items() if s in main for probes in scens.values() for p in probes if not p["ok"] and s == "+novelties"]
    lines += ["", "## Where +novelties still fails", ""]
    for _, p in misses:
        note = f" — {p['note']}" if p["note"] else ""
        answer = " ".join(p["answer"].split())[:220]
        lines.append(f"- **{p['category']}** · “{p['question']}”{note}  \n  > {answer}")
    lines += [
        "",
        "Misses shared by every system come from the core: the hashed embedder knows no synonyms (“phone” vs",
        "“mobile phones”), and the template answerer routes by keywords (“WiFi password in the library” goes to the",
        "library-hours answer). With `--embedder minilm` and an LLM writing the answers those change; the comparisons",
        "between systems are what the benchmark is for.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--embedder", default="hash", help="hash (default, offline, deterministic) or minilm")
    ap.add_argument("--quick", action="store_true", help="main systems only, no ablations or experiments")
    args = ap.parse_args()
    t0 = time.time()
    from . import experiments as x

    probes = scenario_results(MAIN if args.quick else {**MAIN, **ABLATIONS}, args.embedder)
    summary = summarise(probes)
    results = {
        "embedder": args.embedder,
        "main": {s: summary[s] for s in MAIN},
        "ablations": {s: summary[s] for s in ABLATIONS if s in summary},
        "probes": probes,
        "calibration": calibration(probes["+novelties"]),
    }
    if not args.quick:
        script = json.loads((HERE.parent / "tests" / "golden" / "demo_script.json").read_text(encoding="utf-8"))["script"]
        results["experiments"] = {
            "ranking": x.ranking(args.embedder),
            "forgetting": x.forgetting(),
            "consolidation": x.consolidation(),
            "propagation": x.propagation(),
            "counterfactual": x.counterfactual_attribution(script),
            "staleness": x.staleness_check(script),
            "reminders": x.reminders(),
        }
    results["seconds"] = round(time.time() - t0, 1)
    for s, t in results["main"].items():
        print(s.ljust(12), "  ".join(f"{c}={_cell(t, c)}" for c in CATEGORY_LABELS))
    if args.quick:
        return
    suffix = "" if args.embedder == "hash" else f"-{args.embedder}"
    (HERE / f"results{suffix}.json").write_text(json.dumps(results, indent=1, ensure_ascii=False), encoding="utf-8")
    web = HERE.parent.parent / "frontend" / "lib" / "research"
    if not suffix and web.parent.exists():
        # the Research page shows these even when no backend is connected
        web.mkdir(exist_ok=True)
        summary = {k: v for k, v in results.items() if k != "probes"}
        (web / "benchmark.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (HERE / f"RESULTS{suffix}.md").write_text(markdown(results), encoding="utf-8")
    print(f"wrote bench/results{suffix}.json and bench/RESULTS{suffix}.md in {results['seconds']} s")


if __name__ == "__main__":
    main()
